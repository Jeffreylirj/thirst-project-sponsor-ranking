"""Generate the Apps Script benchmark from the reviewed Python model."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scoring.model import load_weights, rank_sponsors, read_evidence


def main():
    weights_path = ROOT / "scoring/weights.json"
    evidence = read_evidence(ROOT / "data/public_evidence.csv")
    ranked = rank_sponsors(evidence, *load_weights(weights_path)).set_index("sponsor")
    rows = []
    for row in evidence.to_dict("records"):
        sponsor = row["sponsor"]
        score = ranked.loc[sponsor, "score"]
        rows.append({
            "sponsor": sponsor, "aliases": [alias for alias in row["aliases"].split("|") if alias],
            "website": row["website"], "email": row["outreach_email"],
            "contactRoute": row["contact_type"], "contactSource": row["contact_url"],
            "review": row["eligibility"] in {"review", "exclude"},
            "score": None if score != score else float(score),
            "criteria": {key: {
                "level": int(row[f"{key}_level"]) if row[f"{key}_level"] else None,
                "reason": row[f"{key}_reason"],
                "sources": [url.strip() for url in row[f"{key}_url"].split("|") if url.strip()],
            } for key in ("gen_z", "cause", "industry")},
        })
    (ROOT / "web/Benchmark.gs").write_text(
        "// Generated by python web/build.py.\n"
        "const WEIGHT_CONFIG = " + json.dumps(json.loads(weights_path.read_text()), ensure_ascii=False) + ";\n"
        "const BASELINE = " + json.dumps(rows, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
